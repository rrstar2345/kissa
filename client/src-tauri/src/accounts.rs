/// `app_settings` key prefix: the `state` sent with the pending login URL.
const FYERS_STATE_PREFIX: &str = "fyers_state:";

fn fyers_account_parts(acct: &Account) -> Result<(String, String)> {
    if acct.kind != "fyers" {
        return Err(anyhow!("Not a Fyers account"));
    }
    let app_id = meta_str(&acct.meta, "appId").to_string();
    let redirect = meta_str(&acct.meta, "redirectUri").to_string();
    if app_id.is_empty() || redirect.is_empty() {
        return Err(anyhow!("Edit the account and fill in the App ID and Redirect URL first"));
    }
    Ok((app_id, redirect))
}

fn login_url(cfg: &AppConfig, app_id: &str, redirect: &str, state: &str) -> Result<String> {
    let mut url = reqwest::Url::parse(&cfg.fyers.auth_url)
        .map_err(|e| anyhow!("fyers.auth_url in settings.json is invalid: {e}"))?;
    url.query_pairs_mut()
        .append_pair("client_id", app_id)
        .append_pair("redirect_uri", redirect)
        .append_pair("response_type", "code")
        .append_pair("state", state);
    Ok(url.to_string())
}

/// Step 1 (paste mode): the Fyers login URL for this account, with a fresh random `state`
/// that is remembered until the login is completed.
pub async fn fyers_login_url(pool: &SqlitePool, cfg: &AppConfig, id: &str) -> Result<String> {
    let acct = get(pool, id).await?;
    let (app_id, redirect) = fyers_account_parts(&acct)?;
    let state = uuid::Uuid::new_v4().simple().to_string();
    crate::db::set_setting(pool, &format!("{FYERS_STATE_PREFIX}{id}"), &state).await?;
    login_url(cfg, &app_id, &redirect, &state)
}

/// What the user pasted after logging in: the full redirected URL
/// (`...?s=ok&code=200&auth_code=...&state=...`) or just the auth code.
/// Returns (auth_code, state if the URL carried one).
fn parse_auth_input(input: &str) -> Result<(String, Option<String>)> {
    let input = input.trim().trim_matches(|c| c == '"' || c == '\'');
    if input.is_empty() {
        return Err(anyhow!("Paste the URL you were redirected to after logging in"));
    }
    if let Ok(url) = reqwest::Url::parse(input) {
        let get = |k: &str| url.query_pairs().find(|(key, _)| key == k).map(|(_, v)| v.to_string());
        if let Some(code) = get("auth_code").filter(|c| !c.is_empty()) {
            return Ok((code, get("state")));
        }
        let detail = get("message").or_else(|| get("s")).unwrap_or_default();
        return Err(anyhow!("That URL has no auth_code{}", if detail.is_empty() { String::new() } else { format!(" ({detail})") }));
    }
    if input.contains(char::is_whitespace) || input.contains('=') {
        return Err(anyhow!("Could not find an auth_code in what was pasted"));
    }
    Ok((input.to_string(), None))
}

/// `appIdHash` = SHA-256 of `app_id:app_secret`, lowercase hex.
fn app_id_hash(app_id: &str, app_secret: &str) -> String {
    use sha2::{Digest, Sha256};
    format!("{:x}", Sha256::digest(format!("{app_id}:{app_secret}").as_bytes()))
}

/// Step 2: verify `state`, exchange the auth code for an access token and keep
/// it in the OS keychain.
pub async fn fyers_login(pool: &SqlitePool, cfg: &AppConfig, id: &str, pasted: &str) -> Result<()> {
    let acct = get(pool, id).await?;
    let (app_id, _) = fyers_account_parts(&acct)?;
    let secret = secrets::get(id, "appSecret")?
        .ok_or_else(|| anyhow!("Secret ID is not set. Edit the account and enter it."))?;

    let (code, state) = parse_auth_input(pasted)?;
    if let Some(state) = state {
        let expected = crate::db::get_setting(pool, &format!("{FYERS_STATE_PREFIX}{id}")).await?;
        if expected.as_deref() != Some(state.as_str()) {
            return Err(anyhow!(
                "The login does not match this request (state differs). Click “Open Fyers login” again and use the newest URL."
            ));
        }
    }

    fyers_exchange(pool, cfg, id, &acct, &app_id, &secret, &code).await
}

/// Exchange an auth code for an access token and keep it in the OS keychain.
async fn fyers_exchange(
    pool: &SqlitePool,
    cfg: &AppConfig,
    id: &str,
    acct: &Account,
    app_id: &str,
    secret: &str,
    code: &str,
) -> Result<()> {
    let resp = http()?
        .post(&cfg.fyers.validate_url)
        .json(&json!({
            "grant_type": "authorization_code",
            "appIdHash": app_id_hash(app_id, secret),
            "code": code,
        }))
        .send()
        .await
        .map_err(|e| anyhow!("Could not reach Fyers: {e}"))?;
    let status = resp.status();
    let text = resp.text().await?;
    let v: Value = serde_json::from_str(&text).map_err(|_| {
        anyhow!("Fyers returned an unexpected response (HTTP {status}): {}", text.chars().take(200).collect::<String>())
    })?;
    let token = v.get("access_token").and_then(Value::as_str).filter(|t| !t.is_empty());
    if v.get("s").and_then(Value::as_str) != Some("ok") || token.is_none() {
        let msg = v.get("message").and_then(Value::as_str).filter(|m| !m.is_empty());
        return Err(anyhow!(
            "Fyers rejected the login: {} (the auth code is single-use and short-lived; log in again for a new one)",
            msg.map(String::from).unwrap_or_else(|| format!("HTTP {status}"))
        ));
    }

    secrets::set(id, "accessToken", token.unwrap_or_default())?;
    invalidate_fyers_auth();
    let now = Utc::now().to_rfc3339();
    mark_token_saved(pool, id, &now).await?;
    // A new token restarts the expiry reminders.
    sqlx::query("DELETE FROM app_settings WHERE key = ?")
        .bind(format!("{TOKEN_NOTIFIED_PREFIX}{id}"))
        .execute(pool)
        .await?;
    sqlx::query("DELETE FROM app_settings WHERE key = ?")
        .bind(format!("{FYERS_STATE_PREFIX}{id}"))
        .execute(pool)
        .await?;

    // `secret_fields` bookkeeping so the UI shows the token as saved.
    let mut set_fields = acct.secrets_set.clone();
    if !set_fields.iter().any(|f| f == "accessToken") {
        set_fields.push("accessToken".into());
        sqlx::query("UPDATE accounts SET secret_fields = ?, updated_at = ? WHERE id = ?")
            .bind(serde_json::to_string(&set_fields)?)
            .bind(&now)
            .bind(id)
            .execute(pool)
            .await?;
    }
    Ok(())
}

// --- local redirect listener -------------------------------------------------
// When the redirect URL is http://127.0.0.1:<port>[/path], the app listens on
// that port for the browser redirect, so nothing needs to be pasted.

const LOGIN_TIMEOUT: Duration = Duration::from_secs(300);

fn pending_logins() -> &'static std::sync::Mutex<HashMap<String, std::sync::Arc<tokio::sync::Notify>>> {
    static P: std::sync::OnceLock<std::sync::Mutex<HashMap<String, std::sync::Arc<tokio::sync::Notify>>>> =
        std::sync::OnceLock::new();
    P.get_or_init(Default::default)
}

/// (port, path) when the redirect URL is a plain `http://127.0.0.1:<port>` URL.
fn loopback_target(redirect: &str) -> Option<(u16, String)> {
    let url = reqwest::Url::parse(redirect).ok()?;
    if url.scheme() != "http" || url.host_str() != Some("127.0.0.1") {
        return None;
    }
    Some((url.port()?, url.path().to_string()))
}

/// Request target of an HTTP request head: `GET /cb?x=1 HTTP/1.1` -> `/cb?x=1`.
fn request_target(head: &str) -> Option<&str> {
    let mut parts = head.lines().next()?.split_whitespace();
    if parts.next()? != "GET" {
        return None;
    }
    parts.next()
}

async fn respond(sock: &mut tokio::net::TcpStream, status: &str, body: &str) {
    use tokio::io::AsyncWriteExt;
    let page = format!(
        "<!doctype html><meta charset=utf-8><title>KISSA</title><body style=\"font-family:sans-serif;padding:2rem\"><h3>{body}</h3>"
    );
    let msg = format!(
        "HTTP/1.1 {status}\r\nContent-Type: text/html; charset=utf-8\r\nContent-Length: {}\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n{page}",
        page.len()
    );
    let _ = sock.write_all(msg.as_bytes()).await;
    let _ = sock.shutdown().await;
}

/// Accept browser requests until one carries the auth code for `state`.
async fn wait_for_code(listener: tokio::net::TcpListener, path: &str, state: &str) -> Result<String> {
    use tokio::io::AsyncReadExt;
    loop {
        let (mut sock, _) = listener.accept().await?;
        let mut buf = vec![0u8; 8192];
        let n = match tokio::time::timeout(Duration::from_secs(3), sock.read(&mut buf)).await {
            Ok(Ok(n)) if n > 0 => n,
            _ => continue,
        };
        let head = String::from_utf8_lossy(&buf[..n]).to_string();
        let Some(target) = request_target(&head) else {
            respond(&mut sock, "405 Method Not Allowed", "Not found").await;
            continue;
        };
        let Ok(url) = reqwest::Url::parse(&format!("http://127.0.0.1{target}")) else {
            respond(&mut sock, "400 Bad Request", "Bad request").await;
            continue;
        };
        if url.path() != path {
            respond(&mut sock, "404 Not Found", "Not found").await; // e.g. /favicon.ico
            continue;
        }
        let get = |k: &str| url.query_pairs().find(|(key, _)| key == k).map(|(_, v)| v.to_string());
        let Some(code) = get("auth_code").filter(|c| !c.is_empty()) else {
            let detail = get("message").unwrap_or_else(|| "no auth_code in the redirect".into());
            respond(&mut sock, "400 Bad Request", "Fyers login failed. You can close this tab.").await;
            return Err(anyhow!("Fyers login failed: {detail}"));
        };
        if get("state").as_deref() != Some(state) {
            respond(&mut sock, "400 Bad Request", "This login does not match the request from KISSA.").await;
            continue;
        }
        respond(&mut sock, "200 OK", "Fyers login complete. You can close this tab and return to KISSA.").await;
        return Ok(code);
    }
}

/// One-click login: listen on the redirect port, open the browser via `open`,
/// wait for Fyers to redirect back, then exchange the code. Gives up after 5 minutes.
pub async fn fyers_login_local<F>(pool: &SqlitePool, cfg: &AppConfig, id: &str, open: F) -> Result<()>
where
    F: FnOnce(&str) -> Result<()> + Send,
{
    let acct = get(pool, id).await?;
    let (app_id, redirect) = fyers_account_parts(&acct)?;
    let (port, path) = loopback_target(&redirect)
        .ok_or_else(|| anyhow!("The Redirect URL is not of the form http://127.0.0.1:<port>"))?;
    let secret = secrets::get(id, "appSecret")?
        .ok_or_else(|| anyhow!("Secret ID is not set. Edit the account and enter it."))?;

    // A new attempt replaces a pending one.
    let cancel = std::sync::Arc::new(tokio::sync::Notify::new());
    let prev = pending_logins().lock().unwrap().insert(id.to_string(), cancel.clone());
    if let Some(prev) = prev {
        prev.notify_one();
        tokio::time::sleep(Duration::from_millis(200)).await;
    }
    let result = async {
        let listener = tokio::net::TcpListener::bind(("127.0.0.1", port)).await.map_err(|e| {
            anyhow!("Could not listen on 127.0.0.1:{port} ({e}). Close whatever uses that port, or register another port in the Fyers app and in this account.")
        })?;
        let state = uuid::Uuid::new_v4().simple().to_string();
        // Also remembered so a pasted redirect URL (fallback) can be verified.
        crate::db::set_setting(pool, &format!("{FYERS_STATE_PREFIX}{id}"), &state).await?;
        open(&login_url(cfg, &app_id, &redirect, &state)?)?;
        let code = tokio::select! {
            r = tokio::time::timeout(LOGIN_TIMEOUT, wait_for_code(listener, &path, &state)) => {
                r.map_err(|_| anyhow!("Timed out waiting for the Fyers login (5 minutes)"))??
            }
            _ = cancel.notified() => return Err(anyhow!("Login cancelled")),
        };
        fyers_exchange(pool, cfg, id, &acct, &app_id, &secret, &code).await
    }
    .await;
    let mut map = pending_logins().lock().unwrap();
    if map.get(id).is_some_and(|c| std::sync::Arc::ptr_eq(c, &cancel)) {
        map.remove(id);
    }
    result
}

pub fn fyers_login_cancel(id: &str) {
    if let Some(c) = pending_logins().lock().unwrap().get(id) {
        c.notify_one();
    }
}

